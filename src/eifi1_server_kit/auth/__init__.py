"""Sign-in, sign-up and the account, as code (``docs/auth-harmonization.md`` §8 in ``Eifi1/ui-kit``).

Layer 1, like the rest of the kit: pure functions, Pydantic models and small classes —
no database, no app ``User``, no routes, and no JWT signing (each app keeps its JWT
library; :mod:`~eifi1_server_kit.auth.tokens` builds and checks the claims). keksdose is
the reference, cited ``file`` per rule.

* :mod:`~eifi1_server_kit.auth.accounts` — the address and its tag, invitations, the
  registration gate, names, erasure identifiers;
* :mod:`~eifi1_server_kit.auth.tokens` — one-time tokens (reset, verification,
  invitation, email change), the session's claims, and what a refresh answers;
* :mod:`~eifi1_server_kit.auth.limits` — :class:`AuthLimiters`, with the per-address
  delay that never locks out;
* :mod:`~eifi1_server_kit.auth.passwords` — :func:`absent_account_check`, the dummy hash an
  address with no account is checked against, so it costs what one with an account costs;
* :mod:`~eifi1_server_kit.auth.totp` — the second factor's code: the time step it matches
  (:func:`totp_matched_step`), the replay rule, a step accepted once
  (:func:`totp_step_accepted`), and one 2FA challenge for one sign-in
  (:func:`two_factor_challenge_claims`, :func:`two_factor_challenge_is_spent`);
* :mod:`~eifi1_server_kit.auth.sessions` — a session's life on the server (0.27):
  :class:`SessionPolicy`, a shared computer's short session (:func:`session_expired`,
  :func:`refresh_lifetime`, :func:`access_lifetime`, :func:`session_expires_at`);
* :mod:`~eifi1_server_kit.auth.schemas` — the wire shapes, with the account's text size
  and contrast (``docs/text-size-harmonization.md`` §6);
* :mod:`~eifi1_server_kit.auth.errors` — :class:`AuthError` and its codes.
"""

